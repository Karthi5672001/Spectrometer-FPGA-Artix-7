-------------------------------------------------------------------------------
-- FILE: 00_hardware_config.vhd
--
-- PURPOSE:
--   Defines the hardware-dependent timing and size constants used throughout
--   the Artix-7 spectrometer firmware.
--
-- ROLE IN THE SPECTROMETER FIRMWARE:
--   This package provides one central location for parameters that describe:
--
--     - FPGA internal clock frequencies
--     - Detector clock frequency
--     - UART baud rates
--     - UART clock-divider values
--     - Number of spectrum pixels
--     - Integration-time limits and defaults
--     - Detector and ADC timing delays
--     - Target spectrum repetition rate
--
--   Other VHDL modules import these constants using:
--
--       use work.hardware_config.all;
--
--   Centralizing the settings prevents timing values from being duplicated
--   across several modules and ensures that the command controller, detector
--   interface, UARTs, frame transmitter, and scheduler use consistent values.
--
-- IMPORTANT:
--   If a clock frequency or UART baud rate is changed, regenerate the Vivado
--   Clocking Wizard and rerun all simulations, synthesis, implementation,
--   timing analysis, and hardware tests.
-------------------------------------------------------------------------------

library IEEE;

-- Provides std_logic definitions. The current package mainly contains numeric
-- constants, but including STD_LOGIC_1164 keeps the package ready for future
-- hardware configuration constants that may use std_logic or vectors.
use IEEE.STD_LOGIC_1164.ALL;


-------------------------------------------------------------------------------
-- HARDWARE CONFIGURATION PACKAGE
-------------------------------------------------------------------------------

package hardware_config is

    ---------------------------------------------------------------------------
    -- FPGA CLOCK FREQUENCIES
    ---------------------------------------------------------------------------

    ---------------------------------------------------------------------------
    -- Main system/control clock frequency.
    --
    -- Generated by the Vivado Clocking Wizard from the Cmod A7 12 MHz board
    -- oscillator.
    --
    -- Used by:
    --   - Command UART receiver
    --   - Command decoder
    --   - Command controller
    --   - Acquisition scheduler
    --   - Detector integration timing controller
    --
    -- Calculation:
    --
    --     10 MHz = 10,000,000 clock cycles per second
    --     One system-clock cycle = 100 ns
    ---------------------------------------------------------------------------

    constant SYSTEM_CLOCK_HZ :
        natural := 10000000;

    ---------------------------------------------------------------------------
    -- Fast readout and spectrum-transmission clock frequency.
    --
    -- Generated by the Vivado Clocking Wizard from the 12 MHz board clock.
    --
    -- Used by:
    --   - Spectrum RAM Port B
    --   - Binary frame transmitter
    --   - High-speed UART transmitter
    --
    -- Calculation:
    --
    --     60 MHz = 60,000,000 clock cycles per second
    --     One fast-clock cycle is approximately 16.667 ns
    ---------------------------------------------------------------------------

    constant FAST_CLOCK_HZ :
        natural := 60000000;

    ---------------------------------------------------------------------------
    -- Detector clock frequency.
    --
    -- The detector clock is produced by dividing the 10 MHz system clock by
    -- two inside detector_capture.vhd.
    --
    -- The resulting clock is output on GPIO22.
    --
    -- Calculation:
    --
    --     5 MHz = 5,000,000 detector-clock periods per second
    --     One detector-clock period = 200 ns = 0.2 microseconds
    ---------------------------------------------------------------------------

    constant DEVICE_CLOCK_HZ :
        natural := 5000000;


    ---------------------------------------------------------------------------
    -- UART CONFIGURATION
    ---------------------------------------------------------------------------

    ---------------------------------------------------------------------------
    -- Baud rate used by the command UART receiver.
    --
    -- Commands are sent from the Python command-line software to RX_USB.
    --
    -- UART format:
    --   - 1 start bit
    --   - 8 data bits
    --   - No parity
    --   - 1 stop bit
    --
    -- This is normally written as 1,000,000 baud, 8-N-1.
    ---------------------------------------------------------------------------

    constant COMMAND_BAUD :
        natural := 1000000;

    ---------------------------------------------------------------------------
    -- Baud rate used by the spectrum UART transmitter.
    --
    -- Binary spectrum frames leave the FPGA through TX_USB.
    --
    -- At 1 Mbaud with 8-N-1 framing, every transmitted byte requires ten
    -- serial bits:
    --
    --     1,000,000 bits/s / 10 bits/byte = 100,000 bytes/s
    --
    -- A 600-byte spectrum frame therefore requires approximately:
    --
    --     600 / 100,000 = 0.006 seconds = 6 ms
    ---------------------------------------------------------------------------

    constant SPECTRUM_BAUD :
        natural := 1000000;

    ---------------------------------------------------------------------------
    -- Number of 10 MHz system-clock cycles in one command-UART bit.
    --
    -- Calculation:
    --
    --     10,000,000 / 1,000,000 = 10 clocks per bit
    --
    -- Used as the CLKS_PER_BIT generic for uart_rx.
    --
    -- This division must produce an integer. If the clock or baud rate is
    -- changed, verify that the resulting UART timing error is acceptable.
    ---------------------------------------------------------------------------

    constant COMMAND_CLKS_PER_BIT :
        positive := SYSTEM_CLOCK_HZ / COMMAND_BAUD;

    ---------------------------------------------------------------------------
    -- Number of 60 MHz fast-clock cycles in one spectrum-UART bit.
    --
    -- Calculation:
    --
    --     60,000,000 / 1,000,000 = 60 clocks per bit
    --
    -- Used as the CLKS_PER_BIT generic for uart_tx.
    ---------------------------------------------------------------------------

    constant FAST_CLKS_PER_BIT :
        positive := FAST_CLOCK_HZ / SPECTRUM_BAUD;


    ---------------------------------------------------------------------------
    -- SPECTRUM SIZE
    ---------------------------------------------------------------------------

    ---------------------------------------------------------------------------
    -- Number of detector pixels stored and transmitted in one spectrum.
    --
    -- Every pixel is stored as a 16-bit value. The physical ADC produces
    -- 12-bit samples, which are zero-extended to 16 bits.
    --
    -- Pixel payload size:
    --
    --     288 pixels * 2 bytes = 576 bytes
    --
    -- RAM addressing therefore requires at least nine bits:
    --
    --     2^8 = 256, which is too small
    --     2^9 = 512, which is sufficient
    ---------------------------------------------------------------------------

    constant PIXEL_COUNT :
        positive := 288;


    ---------------------------------------------------------------------------
    -- INTEGRATION-TIME CONFIGURATION
    ---------------------------------------------------------------------------

    ---------------------------------------------------------------------------
    -- Default stored integration time in microseconds.
    --
    -- The default is 200 microseconds.
    --
    -- This value is loaded into the integration-time register after reset,
    -- but acquisition remains disabled until the FPGA receives a valid start
    -- or integration-time command from the host.
    --
    -- At a 5 MHz detector clock:
    --
    --     200 us * 5 detector counts/us = 1,000 detector-clock counts
    ---------------------------------------------------------------------------

    constant DEFAULT_INTEGRATION_US :
        natural := 200;

    ---------------------------------------------------------------------------
    -- Minimum accepted integration time in microseconds.
    --
    -- Requests below this value are clamped to 20 microseconds.
    --
    -- At 5 MHz:
    --
    --     20 us * 5 counts/us = 100 detector-clock counts
    ---------------------------------------------------------------------------

    constant MIN_INTEGRATION_US :
        natural := 20;

    ---------------------------------------------------------------------------
    -- Maximum accepted integration time in microseconds.
    --
    -- 20,000,000 microseconds equals 20 seconds.
    --
    -- At 5 MHz:
    --
    --     20,000,000 us * 5 counts/us
    --       = 100,000,000 detector-clock counts
    --
    -- This matches the maximum integration count used by the earlier
    -- spectrometer firmware.
    ---------------------------------------------------------------------------

    constant MAX_INTEGRATION_US :
        natural := 20000000;

    ---------------------------------------------------------------------------
    -- Number of detector-clock periods in one microsecond.
    --
    -- Calculation:
    --
    --     5,000,000 Hz / 1,000,000 us/s = 5 counts/us
    --
    -- The command controller uses this value to convert the host command,
    -- expressed in microseconds, into detector-clock counts.
    --
    -- This calculation assumes DEVICE_CLOCK_HZ is an exact integer multiple
    -- of 1 MHz.
    ---------------------------------------------------------------------------

    constant COUNTS_PER_US :
        natural := DEVICE_CLOCK_HZ / 1000000;


    ---------------------------------------------------------------------------
    -- DETECTOR AND ADC TIMING
    ---------------------------------------------------------------------------

    ---------------------------------------------------------------------------
    -- Number of returned data-clock edges to wait before storing pixel zero.
    --
    -- After the integration/start signal transitions into the detector
    -- readout phase, the returned detector clock may include setup, dummy,
    -- pipeline, or invalid sample periods.
    --
    -- detector_capture.vhd waits for this number of GPIO36 rising edges before
    -- writing the first ADC sample into spectrum RAM.
    --
    -- This value is hardware-specific and was retained from the verified
    -- detector timing implementation.
    ---------------------------------------------------------------------------

    constant FIRST_PIXEL_DELAY :
        natural := 92;

    ---------------------------------------------------------------------------
    -- Compensation applied to detector start/integration timing.
    --
    -- This constant represents fixed detector, synchronization, or pipeline
    -- timing that may need to be removed from the requested integration count.
    --
    -- IMPORTANT:
    --   In the current ground-up detector_capture.vhd implementation, check
    --   whether this constant is actually referenced. If it is not used, it is
    --   retained as a documented hardware timing parameter but has no effect
    --   on synthesized logic.
    ---------------------------------------------------------------------------

    constant START_HIGH_COMPENSATION :
        natural := 48;

    ---------------------------------------------------------------------------
    -- Number of 5 MHz detector-clock periods for which the start signal may
    -- remain low between detector operations.
    --
    -- Calculation:
    --
    --     1,000 counts * 0.2 us/count = 200 us
    --
    -- IMPORTANT:
    --   Verify whether the current detector_capture.vhd references this
    --   constant. If not referenced, this value does not affect the current
    --   state machine and is retained for detector timing documentation or
    --   future use.
    ---------------------------------------------------------------------------

    constant START_LOW_COUNTS :
        natural := 1000;


    ---------------------------------------------------------------------------
    -- TARGET FRAME RATE
    ---------------------------------------------------------------------------

    ---------------------------------------------------------------------------
    -- Minimum number of 10 MHz system-clock cycles between acquisition starts.
    --
    -- Target:
    --
    --     50 spectra per second
    --
    -- Calculation:
    --
    --     10,000,000 cycles/s / 50 spectra/s
    --       = 200,000 cycles/spectrum
    --
    -- At 10 MHz:
    --
    --     200,000 cycles * 100 ns/cycle = 20 ms
    --
    -- The top-level scheduler uses this count as a frame-rate limiter. A new
    -- acquisition is permitted only when:
    --
    --   - acquisition is enabled or a single acquisition is pending;
    --   - detector capture is idle;
    --   - frame transmission is idle; and
    --   - this period has elapsed.
    --
    -- The actual spectrum rate may be below 50 spectra/s if detector capture
    -- or UART transmission takes longer than the 20 ms target interval.
    ---------------------------------------------------------------------------

    constant TARGET_FRAME_PERIOD_CYCLES :
        natural := SYSTEM_CLOCK_HZ / 50;

end package hardware_config;