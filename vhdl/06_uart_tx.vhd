-------------------------------------------------------------------------------
-- FILE: 06_uart_tx.vhd
--
-- PURPOSE:
--   Convert one parallel eight-bit data byte into an asynchronous UART serial
--   waveform.
--
-- UART CONFIGURATION:
--   - One start bit
--   - Eight data bits
--   - No parity
--   - One stop bit
--   - Least-significant data bit transmitted first
--
-- ROLE IN THE SPECTROMETER FIRMWARE:
--
--   Binary spectrum frames follow this path:
--
--       spectrum RAM
--            |
--            v
--       frame_transmitter
--            |
--            | data, valid
--            v
--          uart_tx
--            |
--            | serial UART waveform
--            v
--          TX_USB
--            |
--            v
--       USB-UART bridge
--            |
--            v
--       Python host software
--
--   frame_transmitter.vhd determines which byte should be transmitted.
--   uart_tx is responsible only for serializing that byte using UART timing.
--
-- CURRENT CLOCK AND BAUD SETTINGS:
--
--   Fast clock:
--
--       60 MHz
--
--   UART baud:
--
--       1,000,000 bits per second
--
--   Therefore:
--
--       CLKS_PER_BIT = 60,000,000 / 1,000,000 = 60
--
--   One UART bit lasts:
--
--       60 fast-clock cycles
--
--   One complete 8-N-1 UART byte contains ten serial bits:
--
--       1 start bit + 8 data bits + 1 stop bit = 10 bits
--
--   At 1 Mbaud, one byte therefore requires approximately 10 microseconds.
--
--   A complete 600-byte spectrum frame requires approximately:
--
--       600 bytes * 10 us/byte = 6 ms
--
-- HANDSHAKE:
--
--   valid:
--       The upstream module asserts valid when data contains a byte that should
--       be transmitted.
--
--   ready:
--       uart_tx asserts ready only while the transmitter is in IDLE and able
--       to accept a new byte.
--
--   A byte is accepted when valid and ready are both high at a rising edge of
--   clock.
--
-- IMPORTANT TOP-LEVEL DETAIL:
--
--   The current spectrometer top level uses a gated ready signal for the frame
--   transmitter:
--
--       frame_tx_ready <= tx_ready and not tx_valid;
--
--   This prevents frame_transmitter from advancing twice before uart_tx has
--   registered the current valid byte. Without that gating, hardware testing
--   showed that every second frame byte could be lost.
-------------------------------------------------------------------------------

library IEEE;

-- Provides std_logic, std_logic_vector, and rising_edge.
use IEEE.STD_LOGIC_1164.ALL;


-------------------------------------------------------------------------------
-- ENTITY
-------------------------------------------------------------------------------

entity uart_tx is

    generic (

        -----------------------------------------------------------------------
        -- Number of transmitter-clock cycles in one UART bit period.
        --
        -- Current firmware:
        --
        --     Fast clock = 60 MHz
        --     Baud rate  = 1 MHz
        --
        --     CLKS_PER_BIT = 60
        -----------------------------------------------------------------------

        CLKS_PER_BIT : positive := 60
    );

    port (

        -----------------------------------------------------------------------
        -- Transmitter clock.
        --
        -- In spectrometer_top.vhd this is the 60 MHz fast clock generated by
        -- the Clocking Wizard.
        -----------------------------------------------------------------------

        clock : in std_logic;

        -----------------------------------------------------------------------
        -- Active-high synchronous reset.
        --
        -- Returns the transmitter to IDLE and forces the serial output high.
        -----------------------------------------------------------------------

        reset : in std_logic;

        -----------------------------------------------------------------------
        -- Parallel byte to transmit.
        --
        -- The byte is copied into shift_register when valid is accepted while
        -- ready is high.
        -----------------------------------------------------------------------

        data : in std_logic_vector(7 downto 0);

        -----------------------------------------------------------------------
        -- Input byte-valid indication.
        --
        -- The upstream module asserts valid when data contains a byte that is
        -- ready for transmission.
        -----------------------------------------------------------------------

        valid : in std_logic;

        -----------------------------------------------------------------------
        -- Byte-ready indication.
        --
        -- High:
        --     uart_tx is idle and can accept one byte.
        --
        -- Low:
        --     uart_tx is transmitting a start bit, data bits, or stop bit.
        -----------------------------------------------------------------------

        ready : out std_logic;

        -----------------------------------------------------------------------
        -- UART serial output.
        --
        -- Connected to TX_USB in the top-level module.
        --
        -- The UART line remains at logic high while idle.
        -----------------------------------------------------------------------

        tx : out std_logic
    );

end entity uart_tx;


-------------------------------------------------------------------------------
-- ARCHITECTURE
-------------------------------------------------------------------------------

architecture rtl of uart_tx is

    ---------------------------------------------------------------------------
    -- UART transmitter states
    ---------------------------------------------------------------------------

    type state_type is (

        -----------------------------------------------------------------------
        -- Waiting for a byte.
        --
        -- tx is high and ready is high.
        -----------------------------------------------------------------------

        IDLE,

        -----------------------------------------------------------------------
        -- Transmitting the active-low UART start bit.
        -----------------------------------------------------------------------

        START_BIT,

        -----------------------------------------------------------------------
        -- Transmitting eight data bits, least-significant bit first.
        -----------------------------------------------------------------------

        DATA_BITS,

        -----------------------------------------------------------------------
        -- Transmitting the active-high UART stop bit.
        -----------------------------------------------------------------------

        STOP_BIT
    );

    signal state :
        state_type := IDLE;


    ---------------------------------------------------------------------------
    -- Counts fast-clock cycles within the current UART bit.
    --
    -- The counter counts down from CLKS_PER_BIT - 1 to zero. This holds every
    -- UART bit on tx for exactly CLKS_PER_BIT fast-clock cycles.
    ---------------------------------------------------------------------------

    signal clock_count :
        natural range 0 to CLKS_PER_BIT - 1 := 0;


    ---------------------------------------------------------------------------
    -- Index of the data bit currently being transmitted.
    --
    -- UART sends the least-significant bit first:
    --
    --     bit 0, bit 1, ... bit 7
    ---------------------------------------------------------------------------

    signal bit_index :
        natural range 0 to 7 := 0;


    ---------------------------------------------------------------------------
    -- Stores the complete input byte while it is being transmitted.
    --
    -- This prevents changes on the external data input from affecting a byte
    -- that is already in progress.
    ---------------------------------------------------------------------------

    signal shift_register :
        std_logic_vector(7 downto 0) := (others => '0');

begin

    ---------------------------------------------------------------------------
    -- READY OUTPUT
    --
    -- A new byte may be accepted only while the state machine is idle.
    ---------------------------------------------------------------------------

    ready <= '1' when state = IDLE else '0';


    ---------------------------------------------------------------------------
    -- UART TRANSMITTER
    ---------------------------------------------------------------------------

    UART_TRANSMITTER : process(clock)
    begin

        if rising_edge(clock) then

            -------------------------------------------------------------------
            -- Synchronous reset
            -------------------------------------------------------------------

            if reset = '1' then

                state <= IDLE;

                -- UART idle level is high.
                tx <= '1';

                clock_count <= 0;

                bit_index <= 0;

                shift_register <=
                    (others => '0');


            -------------------------------------------------------------------
            -- Normal transmission
            -------------------------------------------------------------------

            else

                case state is

                    -----------------------------------------------------------
                    -- IDLE
                    --
                    -- Hold the UART output high while waiting for a byte.
                    --
                    -- Because ready is high during IDLE, valid = '1' means the
                    -- current data byte is accepted on this clock edge.
                    -----------------------------------------------------------

                    when IDLE =>

                        tx <= '1';

                        clock_count <= 0;

                        bit_index <= 0;

                        if valid = '1' then

                            ---------------------------------------------------
                            -- Store the byte so that it remains stable during
                            -- the complete serial transmission.
                            ---------------------------------------------------

                            shift_register <= data;

                            ---------------------------------------------------
                            -- Begin the start bit immediately.
                            ---------------------------------------------------

                            tx <= '0';

                            clock_count <=
                                CLKS_PER_BIT - 1;

                            state <= START_BIT;

                        end if;


                    -----------------------------------------------------------
                    -- START_BIT
                    --
                    -- The start bit is logic low for exactly CLKS_PER_BIT
                    -- transmitter-clock cycles.
                    -----------------------------------------------------------

                    when START_BIT =>

                        tx <= '0';

                        if clock_count = 0 then

                            ---------------------------------------------------
                            -- Move from the start bit to data bit zero.
                            ---------------------------------------------------

                            bit_index <= 0;

                            tx <= shift_register(0);

                            clock_count <=
                                CLKS_PER_BIT - 1;

                            state <= DATA_BITS;

                        else

                            clock_count <=
                                clock_count - 1;

                        end if;


                    -----------------------------------------------------------
                    -- DATA_BITS
                    --
                    -- Hold each of the eight data bits on tx for exactly one
                    -- UART bit period.
                    -----------------------------------------------------------

                    when DATA_BITS =>

                        if clock_count = 0 then

                            clock_count <=
                                CLKS_PER_BIT - 1;

                            if bit_index = 7 then

                                ------------------------------------------------
                                -- All eight data bits have been transmitted.
                                -- Begin the active-high stop bit.
                                ------------------------------------------------

                                tx <= '1';

                                state <= STOP_BIT;

                            else

                                ------------------------------------------------
                                -- Advance to the next data bit.
                                --
                                -- bit_index is a signal, so
                                -- shift_register(bit_index + 1) selects the
                                -- next bit using the current bit_index value.
                                ------------------------------------------------

                                bit_index <=
                                    bit_index + 1;

                                tx <=
                                    shift_register(bit_index + 1);

                            end if;

                        else

                            clock_count <=
                                clock_count - 1;

                        end if;


                    -----------------------------------------------------------
                    -- STOP_BIT
                    --
                    -- Hold the serial line high for one complete UART bit.
                    --
                    -- After the stop bit, return to IDLE. The ready output will
                    -- then become high and the next byte can be accepted.
                    -----------------------------------------------------------

                    when STOP_BIT =>

                        tx <= '1';

                        if clock_count = 0 then

                            state <= IDLE;

                        else

                            clock_count <=
                                clock_count - 1;

                        end if;

                end case;

            end if;

        end if;

    end process UART_TRANSMITTER;

end architecture rtl;
